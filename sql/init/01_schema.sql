-- Схема хранилища логов форума. Выполняется один раз при первом старте контейнера postgres (пустой том).
-- Слои: raw (как сгенерировано) → stg (очищено за период) → int (дневные метрики) → mart (витрина для CSV).
-- Обоснование партиционирования и индексов — README.md.
SET TIME ZONE 'UTC';

CREATE SCHEMA raw;    -- источник: пишет только forum_data_generation
CREATE SCHEMA stg;    -- очистка и сессии за период: пишет extract_raw_logs
CREATE SCHEMA int;    -- дневные метрики: пишет transform_aggregates
CREATE SCHEMA mart;   -- витрина: пишет transform_aggregates, читает export_to_csv

-- ======================= RAW =======================

CREATE TABLE raw.users (
    id            bigint      PRIMARY KEY,
    username      text        NOT NULL UNIQUE,
    email         text        NOT NULL UNIQUE,
    registered_at timestamptz NOT NULL
);
COMMENT ON TABLE raw.users IS 'Зарегистрированные пользователи форума';

CREATE TABLE raw.forum_logs (
    id           bigint      GENERATED BY DEFAULT AS IDENTITY,
    user_id      bigint      REFERENCES raw.users (id),            -- NULL = аноним
    session_id   uuid,                                             -- одна сессия: login … logout
    action_type  text        NOT NULL CHECK (action_type IN ('first_visit', 'register', 'login', 'logout',
                                                             'create_topic', 'view_topic', 'delete_topic', 'write_message')),
    object_type  text        CHECK (object_type IN ('topic', 'message')),
    object_id    bigint,                                           -- id темы или сообщения
    status       text        NOT NULL CHECK (status IN ('success', 'error')),   -- ответ сервера
    error_code   text,                                             -- AUTH_REQUIRED, …
    event_time   timestamptz NOT NULL,                             -- ключ партиционирования
    metadata     jsonb       NOT NULL DEFAULT '{}'::jsonb,         -- visitor_id, user_agent и т. п.
    loaded_at    timestamptz NOT NULL DEFAULT now(),
    -- уникальный ключ партиционированной таблицы обязан содержать ключ партиции
    PRIMARY KEY (id, event_time),
    -- ответ сервера: ошибка всегда с кодом, успех — без кода
    CONSTRAINT error_code_matches_status CHECK ((status = 'error') = (error_code IS NOT NULL)),
    -- требование 1.1: тему создаёт только залогиненный (попытка анонима логируется как ошибка)
    CONSTRAINT topic_create_needs_login CHECK (NOT (action_type = 'create_topic' AND status = 'success' AND user_id IS NULL)),
    -- сессия бывает только у залогиненного
    CONSTRAINT session_needs_user CHECK (session_id IS NULL OR user_id IS NOT NULL)
) PARTITION BY RANGE (event_time);
COMMENT ON TABLE raw.forum_logs IS 'Логи действий пользователей форума. Партиция на календарный месяц (UTC): raw.forum_logs_YYYY_MM';

-- страховка: строка без своей партиции не теряется; в норме пустая (это проверяет загрузка)
CREATE TABLE raw.forum_logs_default PARTITION OF raw.forum_logs DEFAULT;
-- месячные партиции создаёт задача load_to_postgres перед загрузкой месяца

-- Индексы создаются на родителе — PostgreSQL сам создаёт их в каждой партиции, в том числе в будущих.
-- 1) истории пользователя, D1 retention (EXISTS по user_id в следующем дне)
CREATE INDEX forum_logs_user_time    ON raw.forum_logs (user_id, event_time);
-- 2) дневные агрегаты по типу действия: сообщения, темы, регистрации за день
CREATE INDEX forum_logs_action_time  ON raw.forum_logs (action_type, event_time);
-- 3) сессии: login и logout одной сессии (длительность). Частичный: у анонимов session_id нет
CREATE INDEX forum_logs_session_time ON raw.forum_logs (session_id, event_time) WHERE session_id IS NOT NULL;
-- 4) всё про одну тему или сообщение (кто смотрел, когда удалили)
CREATE INDEX forum_logs_object       ON raw.forum_logs (object_type, object_id) WHERE object_id IS NOT NULL;
-- 5) ошибки за период (create_topic без логина, алертинг). Частичный: ошибок мало
CREATE INDEX forum_logs_errors_time  ON raw.forum_logs (event_time) WHERE status = 'error';

-- ======================= STG =======================

CREATE TABLE stg.forum_logs_daily (
    id          bigint      PRIMARY KEY,
    user_id     bigint,
    session_id  uuid,
    action_type text        NOT NULL,
    object_type text,
    object_id   bigint,
    status      text        NOT NULL,
    error_code  text,
    event_time  timestamptz NOT NULL,
    event_date  date        NOT NULL      -- день по UTC: один фильтр по дате на весь пайплайн
);
CREATE INDEX stg_logs_date_action ON stg.forum_logs_daily (event_date, action_type);
COMMENT ON TABLE stg.forum_logs_daily IS 'Логи за обрабатываемый период плюс день до него (для LAG и D1 retention)';

CREATE TABLE stg.sessions (
    session_id   uuid        PRIMARY KEY,
    user_id      bigint      NOT NULL,
    login_at     timestamptz NOT NULL,
    logout_at    timestamptz NOT NULL,
    duration_sec numeric(12, 2) NOT NULL CHECK (duration_sec >= 0),
    logout_date  date        NOT NULL      -- сессия относится к дню выхода
);
CREATE INDEX stg_sessions_logout_date ON stg.sessions (logout_date);
COMMENT ON TABLE stg.sessions IS 'Завершённые сессии: login и logout склеены по session_id';

-- ======================= INT =======================

CREATE TABLE int.day_metrics (
    day             date    PRIMARY KEY,
    new_accounts    integer NOT NULL,
    total_messages  integer NOT NULL,
    anon_messages   integer NOT NULL,
    total_topics    integer NOT NULL,     -- создано тем за день
    closed_sessions integer NOT NULL,
    sum_session_sec numeric(14, 2) NOT NULL
);
COMMENT ON TABLE int.day_metrics IS 'Одна строка = один день: счётчики без оконных функций';

CREATE TABLE int.retention_cohorts (
    reg_day     date    NOT NULL,
    user_id     bigint  NOT NULL,
    returned_d1 boolean NOT NULL,
    PRIMARY KEY (reg_day, user_id)
);
COMMENT ON TABLE int.retention_cohorts IS 'Кто зарегистрировался в reg_day и вернулся ли в reg_day + 1';

-- ======================= MART =======================

CREATE TABLE mart.forum_daily_stats (
    day                      date          PRIMARY KEY,
    new_accounts             integer       NOT NULL,
    anon_messages_pct        numeric(5, 2),            -- NULL: в этот день не было сообщений
    total_messages           integer       NOT NULL,
    topics_growth_pct        numeric(8, 2),            -- NULL: накануне не создали ни одной темы
    avg_session_duration_sec numeric(10, 2),           -- NULL: в этот день не закончилась ни одна сессия
    d1_retention_pct         numeric(5, 2),            -- NULL: накануне никто не зарегистрировался
    built_at                 timestamptz   NOT NULL DEFAULT now()
);
COMMENT ON TABLE mart.forum_daily_stats IS 'Итоговый датасет: одна строка = один день, выгружается в CSV';
